// Object
// arrays are good but not sufficient 
// for real world

// Creating an Object

const person = {
 name: "Harshit",
 age: 22,
 hobbies: ["guitar", "sleeping", "music"]
};
console.log(person);

// Access data from object
const student = {
 name: "Asma",
 age: 20,
};
console.log(student.name);
console.log(student.age);

// add key-value pair to object
const car = {
    brand: "Toyota",
    model: "Corolla"
};
car.color = "Black";
car.year = 2024;
console.log(car);
